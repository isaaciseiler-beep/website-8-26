create table if not exists public.assistant_feedback (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  request_id text not null,
  session_hash text not null,
  rating text not null check (rating in ('up', 'down')),
  reason text,
  route text,
  intent text,
  model text,
  latency_ms integer,
  source_ids text[] not null default '{}',
  question_hash text not null,
  question text,
  answer text
);

create index if not exists assistant_feedback_created_at_idx
  on public.assistant_feedback (created_at desc);

create index if not exists assistant_feedback_request_id_idx
  on public.assistant_feedback (request_id);

alter table public.assistant_feedback enable row level security;

comment on table public.assistant_feedback is
  'Anonymous quality feedback inserted only by the server with the Supabase service role.';
